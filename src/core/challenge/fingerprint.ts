import type { Challenge } from '../model/types';

/** JSON with object keys sorted at every depth, so key order never changes it. */
export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>)
      .filter(([, v]) => v !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

/** cyrb53: a 53-bit string hash, fast and good enough to notice an edit. Not a seal. */
function hash53(text: string): number {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

/** Over every field but the fingerprint itself. */
export function challengeFingerprint(challenge: Challenge): string {
  return hash53(canonicalJson({ ...challenge, fingerprint: undefined }))
    .toString(16)
    .padStart(14, '0');
}

/** False on a draft: nothing was set, so nothing can have changed since. */
export function challengeChanged(challenge: Challenge): boolean {
  return (
    challenge.fingerprint !== undefined && challenge.fingerprint !== challengeFingerprint(challenge)
  );
}
